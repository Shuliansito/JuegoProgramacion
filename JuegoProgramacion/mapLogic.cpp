void dibujarMapa(string mapa[], int filas)
{
    cout << "\033[0m";
    cout << BG_NO;
    
    
    cout << BG_NO;
    if (mapa == level0) {
        for (int y = 0; y < filas; y++)
        {
            gotoxy(25, 3 + y);

            for (int x = 0; x < mapa[y].size(); x++)
            {
                switch (mapa[y][x])
                {

                case '%': std::cout << BG_NO << BLANCO << "▓"<<RESET; break;

                default:  std::cout << BG_NO  << mapa[y][x] << RESET;
                }


            }
        }
        gotoxy(60, 11);
        cout << NARANJA<<"ENTER"<<RESET;
        return;
    }
    system("cls");
    for (int y = 0; y < filas; y++)
    {
        gotoxy(25, 3 + y);

        for (int x = 0; x < mapa[y].size(); x++)
        {
            switch (mapa[y][x])
            {

            case 'E': std::cout << BG << VERDE << "▒" << RESET; break;
            case '%': std::cout << BG << PARED << "▓" << RESET; break;
            case '$': std::cout << BG << "▓" << RESET; break;
            case 'D': std::cout << BG << VERDE << "▒" << RESET; break;
            case 'P': std::cout << BG << LAZUL << "P" << RESET; break;
            case 'X': std::cout << BG << BLANCO << "X" << RESET; break;
            case '.': std::cout << BG_NO << " " << RESET; break;
            default:  std::cout << BG << mapa[y][x] << RESET;
            }
            
        }
        
    }
    gotoxy(0, 0);
    cout << "\033[0m";
    cout << BG_NO;
}